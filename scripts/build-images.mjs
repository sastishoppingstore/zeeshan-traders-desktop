// Builds optimized WebP variants from the supplied photo folder into the SPA's public dir,
// then regenerates apps/web/src/images.ts so every path is typed and never hand-typed.
//
//   node scripts/build-images.mjs [--src images] [--out apps/web/public/images]
import { readdirSync, mkdirSync, writeFileSync, existsSync, statSync, rmSync } from 'node:fs';
import { join, basename, extname } from 'node:path';
import sharp from 'sharp';

const ROOT = process.cwd();
const args = process.argv.slice(2);
const flag = (name, dflt) => {
  const i = args.indexOf(`--${name}`);
  return i >= 0 ? args[i + 1] : dflt;
};
const SRC = join(ROOT, flag('src', 'images'));
const OUT = join(ROOT, flag('out', 'apps/web/public/images'));

// Largest variant is `lg`; `md` is small-screen; `sm` is icon/thumb.
const SIZES = {
  hero: [{ key: 'lg', width: 1280 }, { key: 'md', width: 720 }],
  categories: [{ key: 'lg', width: 600 }, { key: 'md', width: 340 }, { key: 'sm', width: 140 }],
  products: [{ key: 'lg', width: 600 }, { key: 'md', width: 320 }],
  about: [{ key: 'lg', width: 840 }, { key: 'md', width: 460 }, { key: 'sm', width: 120 }],
};
const QUALITY = 55;

const groups = readdirSync(SRC, { withFileTypes: true }).filter((d) => d.isDirectory()).map((d) => d.name);
const registry = {};
let totalBytes = 0;
let fileCount = 0;

// A 43 MB JPEG source tree would blow the Workers asset budget; WebP at these widths must not.
const SIZE_BUDGET_BYTES = 14 * 1024 * 1024;

for (const group of groups) {
  if (!SIZES[group]) {
    console.log(`SKIP unknown group: ${group}`);
    continue;
  }
  const inDir = join(SRC, group);
  const outDir = join(OUT, group);
  mkdirSync(outDir, { recursive: true });
  const files = readdirSync(inDir)
    .filter((f) => ['.jpg', '.jpeg', '.png', '.webp'].includes(extname(f).toLowerCase()))
    .sort();

  for (const file of files) {
    const name = basename(file, extname(file));
    const input = join(inDir, file);
    const entry = {};
    for (const { key, width } of SIZES[group]) {
      const out = join(outDir, `${name}-${width}.webp`);
      const info = await sharp(input)
        .rotate()
        .resize({ width, height: Math.round(width * 0.85), fit: 'cover', withoutEnlargement: true })
        .webp({ quality: key === 'sm' ? 50 : key === 'md' ? 52 : QUALITY, effort: 6, metadata: false })
        .toFile(out);
      totalBytes += info.size;
      fileCount += 1;
      entry[key] = `/images/${group}/${name}-${width}.webp`;
      entry[`${key}Bytes`] = info.size;
      entry.width = info.width;
      entry.height = info.height;
    }
    entry.source = `images/${group}/${file}`;
    registry[`${group}/${name}`] = entry;
  }
}

// Remove stale variants left over from renames so the deploy bundle carries no dead weight.
let removed = 0;
for (const group of Object.keys(SIZES)) {
  const dir = join(OUT, group);
  if (!existsSync(dir)) continue;
  for (const f of readdirSync(dir)) {
    const stem = f.replace(/-\d+\.webp$/, '');
    if (!registry[`${group}/${stem}`]) {
      rmSync(join(dir, f));
      removed += 1;
    }
  }
}

const ts = `// Generated by scripts/build-images.mjs — do not edit by hand.
// Source photos live in \`images/\` (untracked); run \`npm run build:images\` after adding any.
export type ImageVariant = 'lg' | 'md' | 'sm';
export interface ImageAsset {
  lg: string;
  md: string;
  sm?: string;
  lgBytes: number;
  mdBytes: number;
  smBytes?: number;
  width: number;
  height: number;
  source: string;
}
export const IMAGES = ${JSON.stringify(registry, null, 2)} as const;
export type ImageKey = keyof typeof IMAGES;

/** Pick the variant that fits the slot; \`md\` is used for thumbs, cards on small screens and lazy rows. */
export function img(key: ImageKey, variant: ImageVariant = 'lg'): string {
  const asset = IMAGES[key];
  if (!asset) throw new Error(\`Unknown image key: \${String(key)}\`);
  return (asset as any)[variant] ?? asset.md ?? asset.lg;
}
`;
writeFileSync(join(ROOT, 'apps/web/src/images.ts'), ts);

const report = {
  groups,
  photos: Object.keys(registry).length,
  variants: fileCount,
  staleRemoved: removed,
  totalBytes,
  totalMb: +(totalBytes / 1048576).toFixed(2),
};
writeFileSync(join(OUT, 'manifest.json'), JSON.stringify({ ...report, registry }, null, 2));
console.log('IMAGES_OK', JSON.stringify(report));
if (totalBytes > SIZE_BUDGET_BYTES) {
  console.error(`IMAGES_BUDGET_FAIL: ${(totalBytes / 1048576).toFixed(1)} MB > ${(SIZE_BUDGET_BYTES / 1048576).toFixed(0)} MB — lower widths or quality`);
  process.exit(1);
}
void statSync;
