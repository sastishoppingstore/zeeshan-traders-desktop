import { writeFileSync } from 'node:fs';
import {
  BOOKS, CHART_OF_ACCOUNTS, DOC_PREFIXES, EXPENSE_CATEGORIES, MONEY_ACCOUNTS,
  PERMISSIONS, ROLES, BUSINESS_PROFILE,
} from '../packages/shared/src/constants.ts';

const q = (v: unknown): string => {
  if (v === null || v === undefined) return 'NULL';
  if (typeof v === 'number') return String(v);
  return `'${String(v).replace(/'/g, "''")}'`;
};
const j = (v: unknown): string => q(JSON.stringify(v));
const NOW = "'2026-01-01T00:00:00.000Z'"; // deterministic system-seed timestamp (not business data)
const lines: string[] = [
  '-- Generated by scripts/gen-seed.ts — DO NOT EDIT BY HAND.',
  '-- System configuration only. Production catalogue, parties and balances start EMPTY.',
];

for (const r of ROLES) {
  lines.push(`INSERT OR IGNORE INTO roles (id,code,name_ur,name_en,is_system) VALUES (${q('role-' + r.code.toLowerCase())},${q(r.code)},${q(r.ur)},${q(r.en)},1);`);
}
for (const p of PERMISSIONS) {
  lines.push(`INSERT OR IGNORE INTO permissions (code,description_ur) VALUES (${q(p)},${q('')});`);
}
for (const r of ROLES) {
  const perms = r.perms.includes('*') ? PERMISSIONS : (r.perms as string[]);
  for (const p of perms) {
    lines.push(`INSERT OR IGNORE INTO role_permissions (role_id,permission_code) VALUES (${q('role-' + r.code.toLowerCase())},${q(p)});`);
  }
}
for (const a of CHART_OF_ACCOUNTS) {
  lines.push(`INSERT OR IGNORE INTO chart_of_accounts (code,name_ur,name_en,type,parent_code,is_system) VALUES (${q(a.code)},${q(a.ur)},${q(a.en)},${q(a.type)},${q((a as any).parent ? '1200' : null)},1);`);
}
for (const a of MONEY_ACCOUNTS) {
  lines.push(`INSERT OR IGNORE INTO financial_accounts (id,code,name_ur,name_en,type,gl_code,opening_balance_paisa,is_active) VALUES (${q('acct-' + a.code.toLowerCase())},${q(a.code)},${q(a.ur)},${q(a.en)},${q(a.type)},${q(a.gl)},0,1);`);
  lines.push(`INSERT OR IGNORE INTO account_balance (account_id,balance_paisa,updated_at) VALUES (${q('acct-' + a.code.toLowerCase())},0,${NOW});`);
}
lines.push(`INSERT OR IGNORE INTO warehouses (id,code,name_ur,is_default) VALUES ('wh-main','MAIN','مرکزی گودام',1);`);

